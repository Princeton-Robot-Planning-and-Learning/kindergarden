"""Point cloud generation for Dynamic3D MuJoCo environments.

Provides two complementary methods, selectable via ``generate_point_cloud``:

``method="camera"`` (default)
    Back-projects RGB-D renders from one or more named cameras into
    world-frame XYZ + colour.  Faithfully reproduces what the cameras see,
    including occlusions and lighting.  Returns a :class:`PointCloud`.

``method="mesh"``
    Samples points directly from every geom's triangle mesh (mesh, box,
    cylinder, sphere, capsule) and transforms them to world coordinates.
    Gives complete surface coverage with no occlusion or camera dependency.
    Returns a :class:`MeshPointCloud`.  Requires the ``trimesh`` package.

Typical usage
-------------
::

    env = kinder.make("kinder/BalanceBeam3D-o3-v0")
    env.reset(seed=0)

    sim = get_sim_from_env(env)

    # Camera-based — coloured, view-dependent
    pc = generate_point_cloud(sim, method="camera")
    # pc.xyz -> (N, 3) float32 world-frame positions
    # pc.rgb -> (N, 3) uint8  colours [0, 255]

    # Mesh-based — full coverage, no occlusion (requires trimesh)
    mpc = generate_point_cloud(sim, method="mesh", num_points_per_geom=500)
    # mpc.xyz        -> (N, 3) float32 world-frame positions
    # mpc.geom_names -> list of geom/mesh name strings

"""

from __future__ import annotations

import math
from dataclasses import dataclass, field
from typing import Any, Literal, Sequence, Union

import mujoco
import numpy as np
from numpy.typing import NDArray

from kinder.envs.dynamic3d.mujoco_utils import MjSim

# ---------------------------------------------------------------------------
# Public data type
# ---------------------------------------------------------------------------


@dataclass
class PointCloud:
    """Merged, world-frame coloured point cloud from one or more cameras.

    Attributes:
        xyz: (N, 3) float32 array of world-frame XYZ positions.
        rgb: (N, 3) uint8 array of RGB colours in [0, 255].
        camera_indices: (N,) int array mapping each point to its source
            camera index in ``camera_names``.
        camera_names: Ordered list of camera names that contributed points.
    """

    xyz: NDArray[np.float32]
    rgb: NDArray[np.uint8]
    camera_indices: NDArray[np.int32]
    camera_names: list[str] = field(default_factory=list)

    def __len__(self) -> int:
        return int(self.xyz.shape[0])

    def filter_by_camera(self, name: str) -> "PointCloud":
        """Return a new PointCloud with only the points from *name*."""
        if name not in self.camera_names:
            raise ValueError(
                f"Camera '{name}' not in point cloud. "
                f"Available cameras: {self.camera_names}"
            )
        idx = self.camera_names.index(name)
        mask = self.camera_indices == idx
        return PointCloud(
            xyz=self.xyz[mask],
            rgb=self.rgb[mask],
            camera_indices=self.camera_indices[mask],
            camera_names=[name],
        )

    def to_dict(self) -> dict[str, NDArray]:
        """Serialise to a plain dict (e.g. for np.savez)."""
        return {
            "xyz": self.xyz,
            "rgb": self.rgb,
            "camera_indices": self.camera_indices,
        }


@dataclass
class MeshPointCloud:
    """World-frame point cloud sampled directly from scene mesh geometry.

    Generated by ``generate_point_cloud(sim, method="mesh")``.  Unlike a
    camera-based :class:`PointCloud`, every surface is covered regardless
    of camera placement or occlusion, but there is no colour information.

    Attributes:
        xyz: (N, 3) float32 array of world-frame XYZ positions.
        geom_indices: (N,) int32 array mapping each point to its source geom
            index in ``geom_names``.
        geom_names: Ordered list of geom/mesh names that contributed points.
    """

    xyz: NDArray[np.float32]
    geom_indices: NDArray[np.int32]
    geom_names: list[str] = field(default_factory=list)

    def __len__(self) -> int:
        return int(self.xyz.shape[0])

    def filter_by_geom(self, name: str) -> "MeshPointCloud":
        """Return a new MeshPointCloud containing only the points from *name*."""
        if name not in self.geom_names:
            raise ValueError(
                f"Geom '{name}' not in point cloud. "
                f"Available geoms: {self.geom_names}"
            )
        idx = self.geom_names.index(name)
        mask = self.geom_indices == idx
        return MeshPointCloud(
            xyz=self.xyz[mask],
            geom_indices=np.zeros(int(mask.sum()), dtype=np.int32),
            geom_names=[name],
        )

    def to_dict(self) -> dict[str, NDArray]:
        """Serialise to a plain dict (e.g. for np.savez)."""
        return {
            "xyz": self.xyz,
            "geom_indices": self.geom_indices,
            "geom_names": np.array(self.geom_names),
        }


