_MESH_GEOM_TYPES = frozenset(
    [
        mujoco.mjtGeom.mjGEOM_MESH,  # pylint: disable=no-member
        mujoco.mjtGeom.mjGEOM_BOX,  # pylint: disable=no-member
        mujoco.mjtGeom.mjGEOM_CYLINDER,  # pylint: disable=no-member
        mujoco.mjtGeom.mjGEOM_SPHERE,  # pylint: disable=no-member
        mujoco.mjtGeom.mjGEOM_CAPSULE,  # pylint: disable=no-member
    ]
)


def _get_scene_geoms(sim: MjSim) -> list[tuple[int, str, Any]]:
    """Return (geom_id, name, mesh) for every supported geom in the scene."""
    _require_trimesh()
    model = sim.model.mj_model
    result: list[tuple[int, str, Any]] = []

    for geom_id in range(model.ngeom):
        gtype = model.geom_type[geom_id]
        if gtype not in _MESH_GEOM_TYPES:
            continue

        if gtype == mujoco.mjtGeom.mjGEOM_MESH:  # pylint: disable=no-member
            mesh_id = model.geom_dataid[geom_id]
            if mesh_id < 0:
                continue
            raw_name = mujoco.mj_id2name(  # pylint: disable=no-member
                model,
                int(mujoco.mjtObj.mjOBJ_MESH),  # pylint: disable=no-member
                mesh_id,
            )
            name = (raw_name or f"mesh{mesh_id}") + f"_geom{geom_id}"
            trimesh = _require_trimesh()
            mesh = trimesh.Trimesh(
                vertices=model.mesh_vert[
                    model.mesh_vertadr[mesh_id] : model.mesh_vertadr[mesh_id]
                    + model.mesh_vertnum[mesh_id]
                ],
                faces=model.mesh_face[
                    model.mesh_faceadr[mesh_id] : model.mesh_faceadr[mesh_id]
                    + model.mesh_facenum[mesh_id]
                ],
            )
        else:
            raw_name = mujoco.mj_id2name(  # pylint: disable=no-member
                model,
                int(mujoco.mjtObj.mjOBJ_GEOM),  # pylint: disable=no-member
                geom_id,
            )
            name = (raw_name or f"geom{geom_id}") + f"_geom{geom_id}"
            if gtype == mujoco.mjtGeom.mjGEOM_BOX:  # pylint: disable=no-member
                mesh = _make_box_mesh(model, geom_id)
            elif gtype == mujoco.mjtGeom.mjGEOM_CYLINDER:  # pylint: disable=no-member
                mesh = _make_cylinder_mesh(model, geom_id)
            elif gtype == mujoco.mjtGeom.mjGEOM_SPHERE:  # pylint: disable=no-member
                mesh = _make_sphere_mesh(model, geom_id)
            else:  # CAPSULE
                mesh = _make_capsule_mesh(model, geom_id)

        result.append((geom_id, name, mesh))

    return result


def get_scene_meshes(sim: MjSim) -> dict[str, Any]:
    """Return untransformed (local-frame) trimesh objects for every geom.

    Supports ``mjGEOM_MESH``, ``mjGEOM_BOX``, ``mjGEOM_CYLINDER``,
    ``mjGEOM_SPHERE``, and ``mjGEOM_CAPSULE`` geom types.  Geom names are
    suffixed with ``_geomN`` (N = geom index) so that left/right gripper
    fingers sharing a mesh name remain distinct.

    Requires the ``trimesh`` package.

    Args:
        sim: A ``kinder`` :class:`MjSim` instance (already reset).

    Returns:
        Mapping from ``"<mesh_or_geom_name>_geomN"`` to an untransformed
        :class:`trimesh.Trimesh` in the geom's local coordinate frame.
    """
    return {name: mesh for _, name, mesh in _get_scene_geoms(sim)}


def generate_full_point_cloud(
    sim: MjSim,
    *,
    num_points_per_geom: int = 500,
) -> MeshPointCloud:
    """Generate a world-frame point cloud by sampling from scene mesh geometry.

    Builds a trimesh for every supported geom (mesh, box, cylinder, sphere,
    capsule), samples ``num_points_per_geom`` surface points from each, then
    transforms them into world coordinates using the current simulation state.

    Unlike camera-based point clouds, every surface is covered regardless of
    camera placement or occlusion.

    Requires the ``trimesh`` package.

    Args:
        sim: A ``kinder`` :class:`MjSim` instance (already reset and
            forwarded).
        num_points_per_geom: Number of surface points to sample from each
            geom mesh.

    Returns:
        A :class:`MeshPointCloud` with world-frame XYZ positions.
    """
    model = sim.model.mj_model
    data = sim.data.mj_data

    scene_geoms = _get_scene_geoms(sim)

    all_xyz: list[NDArray[np.float32]] = []
    all_idx: list[NDArray[np.int32]] = []
    geom_names: list[str] = []

    for local_idx, (geom_id, name, mesh) in enumerate(scene_geoms):
        body_id = int(model.geom_bodyid[geom_id])
        body_pos = data.xpos[body_id]
        body_mat = data.xmat[body_id].reshape(3, 3)
        body_transform = np.eye(4)
        body_transform[:3, :3] = body_mat
        body_transform[:3, 3] = body_pos

        local_transform = _transform_from_pos_quat(
            model.geom_pos[geom_id], model.geom_quat[geom_id]
        )
        world_transform = body_transform @ local_transform

        pts = mesh.sample(num_points_per_geom)  # (M, 3)
        pts_h = np.hstack([pts, np.ones((len(pts), 1))])
        xyz = (pts_h @ world_transform.T)[:, :3].astype(np.float32)

        all_xyz.append(xyz)
        all_idx.append(np.full(len(xyz), local_idx, dtype=np.int32))
        geom_names.append(name)

    if not all_xyz:
        return MeshPointCloud(
            xyz=np.empty((0, 3), dtype=np.float32),
            geom_indices=np.empty((0,), dtype=np.int32),
            geom_names=[],
        )

    return MeshPointCloud(
        xyz=np.concatenate(all_xyz, axis=0),
        geom_indices=np.concatenate(all_idx, axis=0),
        geom_names=geom_names,
    )


def generate_track_point_cloud(
    sim: MjSim,
    local_points_dict: dict[str, NDArray[np.float32]] | None,
    *,
    num_points_per_geom: int = 500,
) -> tuple[MeshPointCloud, dict[str, NDArray[np.float32]]]:
    """Generate a tracked world-frame point cloud with fixed point identity.

    On the first call (``local_points_dict=None``) samples surface points from
    every geom in local coordinates and stores them.  On every subsequent call
    the *same* local points are re-transformed to their current world positions,
    so point index ``i`` always refers to the same surface location across
    timesteps.

    Args:
        sim: A ``kinder`` :class:`MjSim` instance (already reset and forwarded).
        local_points_dict: ``None`` on the first call; the dict returned by a
            previous call on subsequent calls.
        num_points_per_geom: Number of surface points to sample from each geom
            mesh (only used on the first call).

    Returns:
        ``(MeshPointCloud, local_points_dict)`` — pass ``local_points_dict``
        back on the next call to maintain correspondence.
    """
    _require_trimesh()
    model = sim.model.mj_model
    data = sim.data.mj_data

    if local_points_dict is None:
        base_meshes = get_scene_meshes(sim)
        local_points_dict = {
            name: mesh.sample(num_points_per_geom).astype(np.float32)
            for name, mesh in base_meshes.items()
        }

    all_xyz: list[NDArray[np.float32]] = []
    all_idx: list[NDArray[np.int32]] = []
    geom_names: list[str] = []

    for local_idx, (name, local_pts) in enumerate(local_points_dict.items()):
        geom_id = int(name.rsplit("_geom", 1)[1])

        body_id = int(model.geom_bodyid[geom_id])
        body_transform = np.eye(4)
        body_transform[:3, :3] = data.xmat[body_id].reshape(3, 3)
        body_transform[:3, 3] = data.xpos[body_id]

        world_transform = body_transform @ _transform_from_pos_quat(
            model.geom_pos[geom_id], model.geom_quat[geom_id]
        )

        pts_h = np.hstack([local_pts, np.ones((len(local_pts), 1))])
        xyz = (pts_h @ world_transform.T)[:, :3].astype(np.float32)

        all_xyz.append(xyz)
        all_idx.append(np.full(len(xyz), local_idx, dtype=np.int32))
        geom_names.append(name)

    if not all_xyz:
        return (
            MeshPointCloud(
                xyz=np.empty((0, 3), dtype=np.float32),
                geom_indices=np.empty((0,), dtype=np.int32),
                geom_names=[],
            ),
            local_points_dict,
        )

    return (
        MeshPointCloud(
            xyz=np.concatenate(all_xyz, axis=0),
            geom_indices=np.concatenate(all_idx, axis=0),
            geom_names=geom_names,
        ),
        local_points_dict,
    )


