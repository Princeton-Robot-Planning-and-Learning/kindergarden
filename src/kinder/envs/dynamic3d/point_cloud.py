def generate_point_cloud(
    sim: MjSim,
    method: Literal["camera", "mesh"] = "camera",
    *,
    # Camera-based keyword arguments
    camera_names: Sequence[str] | None = None,
    width: int = 640,
    height: int = 480,
    max_depth: float = 10.0,
    min_depth: float = 0.01,
    # Mesh-based keyword argument
    num_points_per_geom: int = 500,
) -> Union[PointCloud, MeshPointCloud]:
    """Generate a world-frame point cloud using either camera or mesh sampling.

    Args:
        sim: A ``kinder`` :class:`MjSim` instance (already reset and
            forwarded).
        method: ``"camera"`` (default) back-projects RGB-D renders from named
            cameras into a coloured :class:`PointCloud`.  ``"mesh"`` samples
            points from every geom's triangle mesh and returns a
            :class:`MeshPointCloud` with full surface coverage and no
            occlusion (requires ``trimesh``).
        camera_names: *(camera method only)* Camera names to render.  ``None``
            uses every named camera in the model.
        width: *(camera method only)* Render width in pixels.
        height: *(camera method only)* Render height in pixels.
        max_depth: *(camera method only)* Discard points farther than this
            distance (metres).
        min_depth: *(camera method only)* Discard points closer than this
            distance (metres).
        num_points_per_geom: *(mesh method only)* Number of surface points to
            sample from each geom mesh.

    Returns:
        :class:`PointCloud` when ``method="camera"``;
        :class:`MeshPointCloud` when ``method="mesh"``.

    Raises:
        ValueError: For an unknown *method* string.
        ImportError: When ``method="mesh"`` and ``trimesh`` is not installed.
    """
    if method == "camera":
        return generate_scene_point_cloud(
            sim,
            camera_names=camera_names,
            width=width,
            height=height,
            max_depth=max_depth,
            min_depth=min_depth,
        )
    if method == "mesh":
        return generate_full_point_cloud(sim, num_points_per_geom=num_points_per_geom)
    raise ValueError(f"Unknown method '{method}'. Choose 'camera' or 'mesh'.")


